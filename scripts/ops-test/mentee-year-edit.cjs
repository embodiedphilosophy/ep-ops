// Click-through: Ops → Mentee year editing against the mock. Adds a task to November, edits it, removes it and puts it back,
// edits a project step and November's theme. Writes go to the mock only (see out/mock.log).
//   bash scripts/ops-test/run.sh && node scripts/ops-test/mentee-year-edit.cjs
const { chromium } = require('playwright');
const fs = require('fs');
const cookie = fs.readFileSync(__dirname + '/out/cookie.txt', 'utf8').trim();
const B = 'http://localhost:3100/ops/mentee-year';
const ok = (c, m) => { if (!c) { console.error('FAIL', m); process.exitCode = 1; } else console.log('ok', m); };
(async () => {
  const b = await chromium.launch(); const ctx = await b.newContext({ viewport: { width: 1280, height: 900 } });
  await ctx.addCookies([{ name: 'ep_ops', value: cookie, domain: 'localhost', path: '/' }]);
  const p = await ctx.newPage(); const errs = []; p.on('pageerror', e => errs.push(e.message));
  await p.goto(B + '?tab=months');
  const nov = p.locator('#m-2026-11');
  await nov.getByRole('button', { name: '+ Add a task' }).click();
  await nov.locator('.ops-my-edit').getByLabel('Title', { exact: true }).fill('Watch the orientation recording');
  await nov.getByLabel(/A line under it/).fill('Twenty minutes, before the first immersion.');
  await nov.getByLabel(/^Link/).fill('https://ss.embodiedphilosophy.com/c/mentorship');
  await nov.getByRole('button', { name: 'Add to the mentee page' }).click();
  await nov.getByText('Watch the orientation recording').waitFor({ timeout: 15000 });
  ok(true, 'task added and shown in November');
  await p.screenshot({ path: __dirname + '/out/my-edit-task.png', fullPage: false, clip: { x: 0, y: 0, width: 1280, height: 900 } }).catch(() => {});
  await nov.locator('.ops-my-mlist > li', { hasText: 'Watch the orientation' }).getByRole('button', { name: 'Edit' }).click();
  await nov.locator('.ops-my-edit').getByLabel('Title', { exact: true }).fill('Watch the orientation recording (45 min)');
  await nov.locator('.ops-my-edit').getByRole('button', { name: 'Save' }).click();
  await nov.getByText('Watch the orientation recording (45 min)').waitFor({ timeout: 15000 });
  ok(true, 'task edited');
  p.once('dialog', d => d.accept());
  await nov.locator('.ops-my-mlist > li', { hasText: 'Watch the orientation' }).getByRole('button', { name: 'Edit' }).click();
  await nov.locator('.ops-my-edit').getByRole('button', { name: 'Remove from mentee page' }).click();
  await nov.getByText('Watch the orientation').waitFor({ state: 'detached', timeout: 15000 });
  ok(true, 'task removed');
  await nov.getByRole('button', { name: 'Edit theme' }).click();
  await nov.getByLabel(/^Theme/).fill('Education, and what yoga became');
  await nov.getByRole('button', { name: 'Save' }).click();
  await nov.getByText('Education, and what yoga became').first().waitFor({ timeout: 15000 });
  ok(true, 'month theme saved');
  await p.goto(B + '?tab=projects');
  await p.getByText('Put back').waitFor(); ok(true, 'removed task listed at the bottom');
  await p.getByRole('button', { name: 'Put back' }).click();
  await p.getByText('Taken off the mentee page').waitFor({ state: 'detached', timeout: 15000 }); ok(true, 'task put back');
  const first = p.locator('.ops-my-steps.full > li').first();
  await first.getByRole('button', { name: 'Edit' }).click();
  await first.getByLabel(/^Evidence/).fill('Talk them through at your December one-to-one (bring notes)');
  await first.getByRole('button', { name: 'Save' }).click();
  await p.getByText('(bring notes)').waitFor({ timeout: 15000 }); ok(true, 'project step edited');
  await p.getByRole('button', { name: '+ Add a project step' }).click();
  const f = p.locator('.ops-my-edit');
  await f.getByLabel('Date').fill('2027-01-20'); await f.getByLabel('Project').selectOption('talk'); await f.getByLabel('Title').fill('Share your topic with your buddy');
  await p.getByRole('button', { name: 'Add step' }).click();
  await p.getByText('Share your topic with your buddy').waitFor({ timeout: 15000 }); ok(true, 'project step added');
  ok(await p.locator('.ops-my-steps.full > li').count() === 23, '23 steps now (22 seeded + 1)');
  await p.setViewportSize({ width: 390, height: 844 }); await p.goto(B + '?tab=months');
  await p.locator('#m-2026-11').getByRole('button', { name: '+ Add a task' }).click();
  const over = await p.evaluate(() => document.documentElement.scrollWidth > window.innerWidth + 1);
  ok(!over, 'no sideways scroll at phone width with the form open');
  await p.locator('#m-2026-11 .ops-my-edit').screenshot({ path: __dirname + '/out/my-edit-phone.png' });
  ok(!errs.length, 'no page errors ' + errs.join(' | '));
  await b.close();
})();
